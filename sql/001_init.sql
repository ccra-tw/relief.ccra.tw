-- 001 骨架：使用者、角色、區辦、稽核紀錄（#2）
-- 角色與會簽：服管組 2026-10-15 回覆（#1 留言）——社工分須／不須會簽，會簽者為「指定且固定」的一位。

CREATE TABLE IF NOT EXISTS region (          -- 區辦（案號的區辦碼；#3 再補小區與區域碼）
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text NOT NULL UNIQUE,         -- 區辦碼（案號 ZZ）
    name        text NOT NULL,
    active      boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS app_user (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           text UNIQUE,              -- 內部同工：Cloudflare Access 驗證過的協會信箱
    username        text UNIQUE,              -- 教會帳號：本地帳號密碼登入
    pass_hash       text,                     -- password_hash()；內部同工為 NULL
    display_name    text NOT NULL,
    role            text NOT NULL CHECK (role IN (
                        'church_staff','church_pastor',
                        'region_worker','region_head',
                        'hq_worker','hq_head',
                        'accountant','cashier','assistant','admin')),
    region_id       integer REFERENCES region(id),   -- 所屬區辦（區辦社工／主任／社工助理）
    church_oid      text,                     -- 所屬教會（名錄 oid，#4 建 church 表後加外鍵）
    needs_cosign    boolean NOT NULL DEFAULT false,  -- 這位審核者審完要不要會簽
    cosigner_id     integer REFERENCES app_user(id), -- 固定會簽者
    active          boolean NOT NULL DEFAULT true,
    failed_logins   integer NOT NULL DEFAULT 0,
    locked_until    timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CHECK (email IS NOT NULL OR username IS NOT NULL),
    CHECK (NOT needs_cosign OR cosigner_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS audit_log (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          timestamptz NOT NULL DEFAULT now(),
    user_id     integer,                      -- 未登入失敗時為 NULL
    actor       text NOT NULL,                -- 當下的 email 或帳號（使用者被刪也查得到是誰）
    action      text NOT NULL,                -- login / login_fail / logout / view / create / update / review / export …
    target_type text,
    target_id   text,
    detail      jsonb,
    ip          text
);
CREATE INDEX IF NOT EXISTS audit_log_target ON audit_log (target_type, target_id);
CREATE INDEX IF NOT EXISTS audit_log_at ON audit_log (at);
