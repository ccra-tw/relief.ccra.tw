-- 003 教會主檔、名錄新增申請、教會帳號申請、通知佇列（#4）
-- 教會以 CCNDA 教會機構名錄為主檔：本系統只存名錄 oid 與急難專用欄位，名稱地址是名錄的快取（synced_at 記同步時間）。

CREATE TABLE IF NOT EXISTS church (
    oid          text PRIMARY KEY,               -- 名錄 oid（唯一鍵）
    name         text NOT NULL,                  -- 名錄 ocname 快取
    city         text, town text, address text,
    area_id      integer NOT NULL REFERENCES area(id),   -- 所屬區域（決定區辦與案號 X 碼）
    bank_account text,                           -- 收款帳戶
    relief_note  varchar(1000),                  -- 急難備註（1000 字）
    active       boolean NOT NULL DEFAULT true,
    synced_at    timestamptz NOT NULL DEFAULT now(),
    bound_by     integer REFERENCES app_user(id),
    bound_at     timestamptz NOT NULL DEFAULT now()
);

-- 不在名錄的教會：送名錄 add_data；名錄核可並取得 oid 之前，不能提出急難申請
CREATE TABLE IF NOT EXISTS church_add_request (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL, tel text, email text, zipcode text, city text, town text, address text,
    area_id      integer NOT NULL REFERENCES area(id),
    status       text NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','approved','rejected')),
    oid          text,                           -- 名錄核可後填入，並同時建 church
    api_response jsonb,                          -- add_data 回傳（除錯用）
    requested_by integer NOT NULL REFERENCES app_user(id),
    created_at   timestamptz NOT NULL DEFAULT now(),
    decided_at   timestamptz
);

-- 教會帳號申請：區辦社工提出 → 區辦主任核可 → 產生帳號與初始密碼 → 通知
CREATE TABLE IF NOT EXISTS account_request (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_oid   text NOT NULL REFERENCES church(oid),
    username     text NOT NULL,
    display_name text NOT NULL,
    role         text NOT NULL CHECK (role IN ('church_staff','church_pastor')),
    email        text,                           -- 通知用（教會聯絡信箱）
    region_id    integer NOT NULL REFERENCES region(id),
    status       text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
    requested_by integer NOT NULL REFERENCES app_user(id),
    decided_by   integer REFERENCES app_user(id),
    decided_at   timestamptz,
    reject_reason text,
    user_id      integer REFERENCES app_user(id),
    created_at   timestamptz NOT NULL DEFAULT now()
);

-- 通知佇列：各流程只負責「寫一筆要寄的信」，實際寄送在 #9（寄送失敗可重試、可稽核）
CREATE TABLE IF NOT EXISTS notification (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        text NOT NULL,                   -- account_approved / account_rejected / …（對應通知信對象表）
    to_user_id  integer REFERENCES app_user(id),
    to_email    text,
    subject     text NOT NULL,
    body        text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    sent_at     timestamptz,
    error       text
);
