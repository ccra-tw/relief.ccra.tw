-- 004 個案、申請、附件（#5）
-- 身分證號不存明文：idno_hmac 用來找同一個人，idno_enc 是密文，idno_head／idno_last4 只用來遮罩顯示。

CREATE TABLE IF NOT EXISTS person (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idno_hmac   text NOT NULL UNIQUE,
    idno_enc    text NOT NULL,
    idno_head   char(1) NOT NULL,
    idno_last4  char(4) NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS application (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id        integer NOT NULL REFERENCES person(id),
    church_oid       text NOT NULL REFERENCES church(oid),
    region_id        integer NOT NULL REFERENCES region(id),     -- 申請當下教會所屬區辦（區域範圍限縮用）
    kind             text NOT NULL DEFAULT 'new' CHECK (kind IN ('new','change')),
    parent_id        integer REFERENCES application(id),          -- 異動申請指向原案
    status           text NOT NULL DEFAULT 'draft',               -- draft / reviewing / returned / approved / rejected …（#6 定義審核狀態）
    case_no          text UNIQUE,                                 -- 送審時產生 ZZ-X-YYYY-NNN（#6）
    name             text NOT NULL,                               -- 個案姓名（清單顯示用；完整資料在 data）
    data             jsonb NOT NULL,                              -- 申請表其餘欄位（form_spec.php）
    household        jsonb NOT NULL DEFAULT '[]',                 -- 同住家屬；每人的身分證號另以密文存在 idno_enc
    amount_requested integer,
    applicant_id     integer NOT NULL REFERENCES app_user(id),
    applicant_phone  text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    submitted_at     timestamptz,
    opened_at        date                                         -- 開案日＝申請通過日（#6）
);
CREATE INDEX IF NOT EXISTS application_person ON application (person_id);
CREATE INDEX IF NOT EXISTS application_church ON application (church_oid);

-- 派案：他區、服管組關卡派給誰（#6 填入）。被派到的人看得到該案，即使不在自己區辦範圍
CREATE TABLE IF NOT EXISTS assignment (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id integer NOT NULL REFERENCES application(id),
    stage          text NOT NULL,                 -- other_region / hq
    user_id        integer NOT NULL REFERENCES app_user(id),
    assigned_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (application_id, stage)
);

-- 附件：檔案存主機 /var/lib/relief/uploads（不在網站目錄下、不進資料庫），這裡只記中繼資料
CREATE TABLE IF NOT EXISTS attachment (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id integer NOT NULL REFERENCES application(id),
    kind           text NOT NULL CHECK (kind IN ('consent','proof')),
    orig_name      text NOT NULL,
    stored_name    text NOT NULL UNIQUE,
    mime           text NOT NULL,
    size           integer NOT NULL,
    sha256         text NOT NULL,
    uploaded_by    integer NOT NULL REFERENCES app_user(id),
    uploaded_at    timestamptz NOT NULL DEFAULT now(),
    deleted_at     timestamptz
);
