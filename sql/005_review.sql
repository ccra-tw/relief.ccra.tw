-- 005 審核四關、會簽、派案、期數金額、案號流水號（#6）

ALTER TABLE application ADD COLUMN IF NOT EXISTS cosign_user_id integer REFERENCES app_user(id);   -- 非空＝等這位會簽
ALTER TABLE application ADD COLUMN IF NOT EXISTS cosign_for_id  integer REFERENCES app_user(id);   -- 為誰會簽（審核者）

-- 每一個審核動作一筆（取代舊系統 Examine1–7 欄位）
CREATE TABLE IF NOT EXISTS review_step (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id integer NOT NULL REFERENCES application(id),
    stage          text NOT NULL,            -- submit / pastor / region / other_region / hq
    part           text NOT NULL DEFAULT 'review' CHECK (part IN ('review','cosign','submit')),
    user_id        integer NOT NULL REFERENCES app_user(id),
    action         text NOT NULL CHECK (action IN ('submit','approve','return','reject')),
    opinion        text,
    at             timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS review_step_app ON review_step (application_id, id);

-- 期數與核發金額（區辦、他區、服管組審核時配置；第一期必填，需求 0003）
CREATE TABLE IF NOT EXISTS installment (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id integer NOT NULL REFERENCES application(id),
    seq            integer NOT NULL CHECK (seq >= 1),
    amount         integer NOT NULL CHECK (amount > 0),
    set_stage      text NOT NULL,
    set_by         integer NOT NULL REFERENCES app_user(id),
    set_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (application_id, seq)
);

-- 案號流水號：同區辦、同年度不重複
CREATE TABLE IF NOT EXISTS case_seq (
    region_id integer NOT NULL REFERENCES region(id),
    year      integer NOT NULL,
    last      integer NOT NULL DEFAULT 0,
    PRIMARY KEY (region_id, year)
);
