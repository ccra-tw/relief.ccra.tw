-- 006 服務紀錄、結案（#7）。異動申請沿用 application（kind='change'、parent_id 指原案）。
-- 服管組 2026-10-15：「28 天未回凍結」刪除，只做未填提醒（#9），所以這裡沒有凍結欄位。

CREATE TABLE IF NOT EXISTS service_record (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id integer NOT NULL REFERENCES application(id),   -- 原案（kind='new'）
    user_id        integer NOT NULL REFERENCES app_user(id),      -- 填寫的志工（系統帶入登入者）
    data           jsonb NOT NULL,
    served_at      timestamptz NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS service_record_app ON service_record (application_id, served_at);

CREATE TABLE IF NOT EXISTS closure (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id integer NOT NULL REFERENCES application(id),
    close_type     text NOT NULL,
    data           jsonb NOT NULL,                                 -- 結案表單＋結案問卷
    status         text NOT NULL CHECK (status IN ('pending_review','closed','returned','rejected')),
    submitted_by   integer NOT NULL REFERENCES app_user(id),
    submitted_at   timestamptz NOT NULL DEFAULT now(),
    reviewed_by    integer REFERENCES app_user(id),
    reviewed_at    timestamptz,
    review_opinion text
);

ALTER TABLE application ADD COLUMN IF NOT EXISTS closed_at date;   -- 結案日＝教會送出結案報告日
