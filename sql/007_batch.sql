ALTER TABLE application ADD COLUMN IF NOT EXISTS last_paid_at date;

CREATE TABLE IF NOT EXISTS batch (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year        integer NOT NULL,
    no          integer NOT NULL,                        -- 年度內第幾批
    status      text NOT NULL DEFAULT 'confirming' CHECK (status IN ('confirming','sent','paid')),
    created_by  integer NOT NULL REFERENCES app_user(id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    sent_by     integer REFERENCES app_user(id),
    sent_at     timestamptz,
    paid_by     integer REFERENCES app_user(id),
    paid_on     date,
    UNIQUE (year, no)
);

ALTER TABLE installment ADD COLUMN IF NOT EXISTS batch_id        integer REFERENCES batch(id);
ALTER TABLE installment ADD COLUMN IF NOT EXISTS region_confirmed boolean NOT NULL DEFAULT false;
ALTER TABLE installment ADD COLUMN IF NOT EXISTS paid_on         date;
ALTER TABLE installment ADD COLUMN IF NOT EXISTS receipt_back_on date;           -- 領據簽回日
ALTER TABLE installment ADD COLUMN IF NOT EXISTS receipt_by      integer REFERENCES app_user(id);
